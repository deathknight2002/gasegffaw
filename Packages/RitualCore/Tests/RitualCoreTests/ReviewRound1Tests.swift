final class ReviewRound1EdgeTests: XCTestCase {
    /// Attribute each vector's Moon error to the lunar series versus ΔT: re-evaluate the
    /// same Meeus series at Swiss's own TT and compare.
    func testMoonErrorAttributionToDeltaT() {
        print("REVIEW date        ΔT(RC−Swiss)s  Moon Δ(RC ΔT)″  Moon Δ(Swiss ΔT)″  syzygy Δt s")
        var worstSeries = 0.0
        for v in ReviewFixture.vectors {
            let jdTT = JulianDay.terrestrialTime(fromUT: v.jdUT)
            let ownMoon = Ephemeris.moon(jdUT: v.jdUT).longitude
            let swissTT = v.jdUT + v.deltaT / 86_400.0
            let g = Ephemeris.moonMeeusGeometric(jdTT: swissTT)
            let seriesMoon = Angle.normalize(g.longitude + Ephemeris.nutation(jdTT: swissTT).longitude)
            let s = SyzygyFinder.prenatal(before: v.jdUT)
            let dOwn = wrapDiff(ownMoon, v.moonLon) * 3600, dSeries = wrapDiff(seriesMoon, v.moonLon) * 3600
            worstSeries = max(worstSeries, dSeries)
            print(String(format: "REVIEW %@  %8.1f  %8.1f  %8.1f  %8.1f", v.date, JulianDay.deltaT(jd: v.jdUT) - v.deltaT, dOwn, dSeries, abs(s.jdUT - v.syzygyJD) * 86_400))
            _ = jdTT
        }
        print("REVIEW lunar series alone (Swiss ΔT): worst \(worstSeries)″")
        XCTAssertLessThan(worstSeries, 20, "Meeus ch.47 truncation budget is ~10–20″")
    }

    func testSyzygyAndMoonAtThe2100Edge() {
        for (y, m, d, h, jd, sunLon, moonLon, kind, syzJD, syzLon, swissDeltaT) in ReviewFixture.edgeVectors {
            XCTAssertEqual(JulianDay.fromCalendar(year: y, month: m, day: d, hourUT: h), jd, accuracy: 1e-8)
            let dT = JulianDay.deltaT(jd: jd)
            let sun = Ephemeris.sun(jdUT: jd).longitude, moon = Ephemeris.moon(jdUT: jd).longitude
            let s = SyzygyFinder.prenatal(before: jd)
            let dt = abs(s.jdUT - syzJD) * 86_400
            print(String(format: "REVIEW edge %04d-%02d-%02d: ΔT RC %.1f vs Swiss %.1f (Δ %.1f s); Sun Δ %.1f″; Moon Δ %.1f″; syzygy %@ Δt %.1f s Δλ %.2f″", y, m, d, dT, swissDeltaT, dT - swissDeltaT, wrapDiff(sun, sunLon) * 3600, wrapDiff(moon, moonLon) * 3600, s.kind.rawValue, dt, wrapDiff(s.longitude, syzLon) * 3600))
            XCTAssertEqual(s.kind.rawValue == "fullMoon" ? "full" : "new", kind)
            XCTAssertLessThanOrEqual(wrapDiff(sun, sunLon), 0.01, "Sun \(y)-\(m)-\(d)")
            XCTAssertLessThanOrEqual(wrapDiff(moon, moonLon), 0.05, "Moon \(y)-\(m)-\(d)")
            XCTAssertLessThanOrEqual(dt, 120, "CORE_API: prenatal syzygy instant within 2 minutes — \(y)-\(m)-\(d) is off by \(dt) s")
        }
    }

