    func testSigilEnergyNeverRisesUnderRandomFlicksBetweenSteps() {
        var rng = SeededRNG(seed: 2026, stream: 9)
        for scale in [0.0, 0.3, 1.0, 3.0] {
            var s = SigilDynamics()
            for tick in 0..<(120 * 30) {
                if tick % 97 == 0 {
                    s.applyFlick(velocity: RVec2(rng.nextRange(-4, 4), rng.nextRange(-4, 4)), ring: Int(rng.nextU32() % 5))
                }
                let before = s.kineticEnergy
                s.step(dt: 1.0 / 120.0, frictionScale: scale)
                XCTAssertLessThanOrEqual(s.kineticEnergy, before + 1e-12, "energy rose at tick \(tick) scale \(scale)")
                for r in s.rings { XCTAssertFalse(r.omega.isNaN); XCTAssertFalse(r.angle.isNaN) }
            }
        }
    }
