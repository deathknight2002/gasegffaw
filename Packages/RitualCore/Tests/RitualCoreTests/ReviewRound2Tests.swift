        XCTAssertEqual(EmberModel.terminalVelocity(gravity: 0), RVec3(0, 0, 0))
    }

    /// Replays the numpy reference scenarios through `SigilDynamics` and compares every
    /// pinned ring velocity (the two implementations differ only in summation order).
    func testSigilDynamicsMatchesNumpyReimplementation() {
        for (scale, flicks, total, pins) in Round2Fixture.sigilPins {
            var s = SigilDynamics()
            var next = 0
            for n in 0 ..< total {
                for (t, vx, vy, ring) in flicks where t == n { s.applyFlick(velocity: RVec2(vx, vy), ring: ring) }
                s.step(dt: 1.0 / 120.0, frictionScale: scale)
                if next < pins.count, pins[next].0 == n + 1 {
                    for (i, expected) in pins[next].1.enumerated() {
                        XCTAssertEqual(s.rings[i].omega, expected, accuracy: 1e-9, "scale \(scale) step \(n + 1) ring \(i)")
                    }
                    next += 1
                }
            }
            XCTAssertEqual(next, pins.count)
        }
    }

    /// Exact algebra of the documented scheme (viscous + coupling, Coulomb off):
    /// E₁ − E₀ = dt·ωᵀKω + ½dt²·(Kω)ᵀI⁻¹(Kω), with K the symmetric torque matrix. With
    /// Coulomb on, the change can only be more negative. Independent of any pins.
    func testSigilPerStepEnergyIdentity() {
        var rng = SeededRNG(seed: 77, stream: 2)
        for scale in [0.0, 0.5, 1.0, 3.0, 10.0] {
            for _ in 0 ..< 200 {
                var s = SigilDynamics(); s.coulomb = 0
                for i in 0 ..< 5 { s.rings[i].omega = rng.nextRange(-12, 12) }
                let w = s.rings.map(\.omega), inertia = s.rings.map(\.inertia)
                var torque = [Double](repeating: 0, count: 5)
                for i in 0 ..< 5 {
                    torque[i] = -s.viscous * scale * w[i]
                    if i > 0 { torque[i] -= s.coupling * (w[i] + w[i - 1]) }
                    if i < 4 { torque[i] -= s.coupling * (w[i] + w[i + 1]) }
                }
                let dt = 1.0 / 120.0
                var predicted = 0.0
                for i in 0 ..< 5 { predicted += dt * w[i] * torque[i] + 0.5 * dt * dt * torque[i] * torque[i] / inertia[i] }
                let e0 = s.kineticEnergy
                var withCoulomb = s; withCoulomb.coulomb = SigilDynamics.defaultCoulomb
                s.step(dt: dt, frictionScale: scale)
                withCoulomb.step(dt: dt, frictionScale: scale)
                XCTAssertEqual(s.kineticEnergy - e0, predicted, accuracy: 1e-11, "scale \(scale)")
                XCTAssertLessThanOrEqual(predicted, 1e-12, "scheme dissipates for every state at scale \(scale)")
                XCTAssertLessThanOrEqual(withCoulomb.kineticEnergy, s.kineticEnergy + 1e-12, "Coulomb only removes energy")
            }
        }
    }

    /// Ring 0 alone (coupling and Coulomb off) decays as (1 − dt/τ)ⁿ with τ = I₀/viscous = 5.625 s.
    func testSigilViscousTimeConstant() {
        var s = SigilDynamics(); s.coupling = 0; s.coulomb = 0
        s.rings[0].omega = 7.0
        let tau = s.rings[0].inertia / s.viscous
        XCTAssertEqual(tau, 5.625, accuracy: 1e-12)
        let steps = Int((tau * 120).rounded())
        for _ in 0 ..< steps { s.step(dt: 1.0 / 120.0, frictionScale: 1) }
        let ratio = s.rings[0].omega / 7.0
        XCTAssertEqual(ratio, pow(1 - 1.0 / 120.0 / tau, Double(steps)), accuracy: 1e-12)
        XCTAssertEqual(ratio, exp(-1), accuracy: 5e-4)
        // Total sparks over that time follow |ω| r × 40.
        XCTAssertEqual(s.sparkRate, abs(s.rings[0].omega) * 0.75 * 40, accuracy: 1e-12)
    }
